type Ring = readonly number[];

const f = (n: number) => Number(n.toFixed(2));

function ring(points: Ring): string {
  let d = '';
  for (let i = 0; i < points.length; i += 2) {
    d += `${i === 0 ? 'M' : 'L'}${f(points[i]!)} ${f(points[i + 1]!)}`;
  }
  return `${d}Z`;
}

function poly(...rings: Ring[]): string {
  return rings.map(ring).join('');
}

/** Octagon with flat top, centred on cx, cy, circumradius r. */
function oct(cx: number, cy: number, r: number): Ring {
  const out: number[] = [];
  for (let k = 0; k < 8; k += 1) {
    const a = ((22.5 + 45 * k) * Math.PI) / 180;
    out.push(cx + r * Math.cos(a), cy + r * Math.sin(a));
  }
  return out;
}

function rect(x1: number, y1: number, x2: number, y2: number): Ring {
  return [x1, y1, x2, y1, x2, y2, x1, y2];
}

/** A seal: n points, alternating outer and inner radius. */
function seal(cx: number, cy: number, ro: number, ri: number, n: number): Ring {
  const out: number[] = [];
  for (let k = 0; k < n * 2; k += 1) {
    const a = (k * Math.PI) / n - Math.PI / 2;
    const r = k % 2 === 0 ? ro : ri;
    out.push(cx + r * Math.cos(a), cy + r * Math.sin(a));
  }
  return out;
}

/** A wave strip cut with a zigzag: peaks every 3 units, `amp` high, `thick` deep. */
function wave(y: number, amp: number, thick: number): Ring {
  const top: number[] = [];
  for (let x = 2, k = 0; x <= 20; x += 3, k += 1) top.push(x, k % 2 === 0 ? y : y - amp);
  top.push(22, y - amp * 0.6);
  const bottom: number[] = [];
  for (let i = top.length - 2; i >= 0; i -= 2) bottom.push(top[i]!, top[i + 1]! + thick);
  return [...top, ...bottom];
}

/** Window holes in a grid (cols x rows), each w x h, stepping sx and sy. */
function holes(x: number, y: number, cols: number, rows: number, w: number, h: number, sx: number, sy: number): Ring[] {
  const out: Ring[] = [];
  for (let r = 0; r < rows; r += 1) for (let c = 0; c < cols; c += 1) out.push(rect(x + c * sx, y + r * sy, x + c * sx + w, y + r * sy + h));
  return out;
}

