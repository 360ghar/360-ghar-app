//   and the theme vignettes (vignettes.ts).
// - lib/core/design/paper/knife_icons.dart: the knife icons (icons.ts plus appIcons).
// - test/fixtures/paper_fixtures.json: reference output of rng, hash, cutPolygon,
//   cutBandPath, rooflineBandPath and zigzagEdge, used to test the Dart port in
