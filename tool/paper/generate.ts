/** Vignette themes and the places that show them (tools grid, profile purpose choice). */
const VIGNETTE_SEEDS: Record<VignetteTheme, string[]> = {
  calculator: ['tools'],
  key: ['tools', 'purpose'],
  document: ['tools'],
  tower: ['tools'],
  home: ['tools', 'purpose'],
  plot: ['tools'],
  pg: ['purpose'],
};

const str = (s: string) => `'${s}'`;
const path = (d: string) => str(compactPath(d));

function layerDart(l: Layer & { lit?: number[]; counted?: boolean }, indent: string): string {
  const list = (items: string[]) => (items.length ? `[\n${items.map((d) => `${indent}    ${path(d)},`).join('\n')}\n${indent}  ]` : '[]');
  return [
    `${indent}PaperLayerData(`,
    `${indent}  id: ${str(l.id)},`,
    `${indent}  tone: PaperTone.${l.fill},`,
    `${indent}  depth: ${l.depth},`,
    `${indent}  shadow: ${Number(l.shadow)},`,
    `${indent}  cut: ${list(l.cut)},`,
    `${indent}  solid: ${list(l.solid)},`,
    ...(l.lit?.length ? [`${indent}  lit: [${l.lit.join(', ')}],`] : []),
    ...(l.counted ? [`${indent}  counted: true,`] : []),
    `${indent}),`,
  ].join('\n');
}

function artDart(width: number, height: number, shadow: [number, number, number], frame: string | null, layers: Layer[], indent: string): string {
  return [
    `PaperArtData(`,
    `${indent}width: ${width},`,
    `${indent}height: ${height},`,
    `${indent}shadow: (${shadow.join(', ')}),`,
    `${indent}frame: ${frame ? path(frame) : 'null'},`,
    `${indent}layers: [`,
    ...layers.map((l) => layerDart(l, `${indent}  `)),
    `${indent}],`,
    `${indent.slice(2)})`,
  ].join('\n');
}

const scenes: string[] = [];
for (const [name, seeds] of Object.entries(SCENE_SEEDS) as [SceneName, string[]][]) {
  for (const seed of seeds) {
    const frame = makeTools(`edge-scene-${name}-${seed}`, 2.6).rect(3, 3, SCENE_W - 6, SCENE_H - 6);
    scenes.push(`  '${name}/${seed}': ${artDart(SCENE_W, SCENE_H, [2, 3, 1.1], frame, sceneLayers(name, seed), '    ')},`);
  }
}

const headers = Object.entries(headerLayers).map(
  ([name, build]) => `  '${name}': ${artDart(HEADER_W, HEADER_H, [2.4, 3.2, 1.3], null, build(), '    ')},`,
);

const vignettes: string[] = [];
for (const [theme, seeds] of Object.entries(VIGNETTE_SEEDS) as [VignetteTheme, string[]][]) {
  for (const seed of seeds) {
    vignettes.push(`  '${theme}/${seed}': ${artDart(VIGNETTE_W, VIGNETTE_H, [1.4, 2, 0.7], vignetteFrame(theme, seed), vignetteLayers(theme, seed), '    ')},`);
  }
}

